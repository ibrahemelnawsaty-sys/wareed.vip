<?php

namespace App\Support;

use App\Http\Controllers\QuoteController;
use App\Models\ServiceRequest;
use Illuminate\Support\Str;

/**
 * مسوّدة العقد الافتراضية: مواد قياسية معتمدة على أفضل ممارسات عقود
 * الخدمات، تُقترَح تلقائياً عند اعتماد العميل للعرض ويعدّلها الفريق قبل
 * أول إرسال (حذف/تعديل/إضافة أي مادة من لوحة التحكم). هذه مسوّدة تقنية
 * لا استشارة قانونية — تُراجَع قبل اعتمادها فعلياً على عملاء حقيقيين.
 */
class ContractTemplate
{
    /**
     * مواد العقد الافتراضية مبنيّة من بيانات الطلب وعرض السعر الصادر له.
     *
     * @return array<int, array{id: string, section: string, title: string, body: string}>
     */
    public static function draft(ServiceRequest $sr): array
    {
        $quote = QuoteController::quoteOf($sr);
        $clientName = $sr->name ?: 'العميل';
        $clientCompany = $sr->company ?: null;
        $legalName = (string) setting('legal_name', 'وريد لتقنية المعلومات');
        // البرامج التدريبية لها مفرداتها والتزاماتها (منهج ومدرّبون وشهادات ومواد تدريبية)،
        // والمتاجر والحلول التقنية مشروع يُنفَّذ ويُسلَّم
        $training = ServiceFlow::type($sr) === 'training';
        $t = fn (string $project, string $trainingText) => $training ? $trainingText : $project;
        $money = fn ($n, $cur) => number_format((float) $n, ((float) $n == (int) $n) ? 0 : 2).' '.$cur;
        $total = $quote ? $money($quote['total'], $quote['currency']) : '—';
        $timeline = $quote ? ($quote['timeline'] ?: null) : null;
        $deliveryAt = $quote ? $quote['delivery_at']?->format('Y/m/d') : null;

        $items = $quote ? collect($quote['items'])
            ->map(fn ($i) => '- '.$i['name'].($i['qty'] > 1 ? ' (الكمية: '.$i['qty'].($i['unit'] ? ' '.$i['unit'] : '').')' : ''))
            ->implode("\n") : '- تُحدَّد بنود المشروع وفق عرض السعر المعتمد.';

        $pct = fn ($n) => rtrim(rtrim(number_format((float) $n, 2), '0'), '.');
        $payments = $quote && $quote['payments'] ? collect($quote['payments'])
            ->map(fn ($p) => '- '.$p['label'].': '.$pct($p['percent']).'% ('.$money($p['amount'], $quote['currency']).')'.($p['due'] ? ' — تستحق '.$p['due']->format('Y/m/d') : ''))
            ->implode("\n") : '- تُحدَّد الدفعات وفق عرض السعر المعتمد.';

        $clauses = [
            [
                'section' => 'تمهيد',
                'title' => 'المادة الأولى: تعريف الطرفين',
                'body' => "الطرف الأول: {$legalName}، ويُشار إليه في هذا العقد بـ«الشركة».\n"
                    ."الطرف الثاني: {$clientName}".($clientCompany ? " ({$clientCompany})" : '').", ويُشار إليه في هذا العقد بـ«العميل».\n"
                    .'اتفق الطرفان، وهما بكامل الأهلية المعتبرة شرعاً ونظاماً، على إبرام هذا العقد وفق البنود التالية.',
            ],
            [
                'section' => 'تمهيد',
                'title' => $t('المادة الثانية: تعريف المشروع ونطاقه', 'المادة الثانية: تعريف البرنامج ونطاقه'),
                'body' => $t(
                    "يلتزم الطرف الأول بتنفيذ المشروع الموضَّح تفاصيله في عرض السعر المعتمد رقم {$sr->reference}، ويشمل نطاق العمل البنود التالية:\n{$items}\n",
                    "يلتزم الطرف الأول بتقديم البرنامج التدريبي الموضَّح تفاصيله في عرض السعر المعتمد رقم {$sr->reference}، ويشمل نطاق البرنامج المحاور التالية:\n{$items}\n",
                ).'وتُعدّ نسخة عرض السعر المرفقة جزءاً لا يتجزأ من هذا العقد.',
            ],
            [
                'section' => 'الالتزامات',
                'title' => 'المادة الثالثة: التزامات الطرف الأول',
                'body' => "يلتزم الطرف الأول بـ:\n".$t(
                    "- تنفيذ المشروع بالجودة والمواصفات المتفق عليها.\n"
                    ."- الالتزام بالجدول الزمني المحدَّد في هذا العقد.\n"
                    ."- تسليم المشروع كاملاً وفق النطاق المتفق عليه.\n"
                    .'- تقديم الدعم الفني اللازم خلال فترة الضمان المنصوص عليها في هذا العقد.',
                    "- تقديم البرنامج وفق المنهج والمدة المتفق عليهما.\n"
                    ."- توفير مدرّبين مؤهّلين والمواد التدريبية اللازمة.\n"
                    ."- إصدار شهادات إتمام للمتدربين المستوفين لشروط الحضور.\n"
                    .'- تقديم الدعم للمتدربين خلال فترة البرنامج.',
                ),
            ],
            [
                'section' => 'الالتزامات',
                'title' => 'المادة الرابعة: التزامات الطرف الثاني',
                'body' => "يلتزم الطرف الثاني بـ:\n".$t(
                    "- سداد المقابل المالي وفق الجدول المتفق عليه في هذا العقد.\n"
                    ."- تزويد الطرف الأول بالمعلومات والمواد اللازمة لتنفيذ المشروع في وقتها.\n"
                    .'- الردّ على طلبات المراجعة والاعتماد خلال مدة معقولة لضمان سير العمل دون تأخير.',
                    "- سداد المقابل المالي وفق الجدول المتفق عليه في هذا العقد.\n"
                    ."- تزويد الطرف الأول بقائمة المتدربين وبياناتهم في وقتها.\n"
                    .'- توفير مكان التدريب وتجهيزاته إن كان حضورياً لدى الطرف الثاني، والتزام المتدربين بمواعيد البرنامج.',
                ),
            ],
            [
                'section' => 'التنفيذ',
                'title' => 'المادة الخامسة: الجدول الزمني',
                'body' => $deliveryAt
                    ? $t(
                        "موعد التسليم المستهدف لإتمام المشروع هو {$deliveryAt}، ما لم يطرأ ما يستوجب تمديده باتفاق الطرفين كتابةً.",
                        "موعد ختام البرنامج المستهدف هو {$deliveryAt}، ما لم يطرأ ما يستوجب تمديده باتفاق الطرفين كتابةً.",
                    )
                    : ($timeline
                        ? $t(
                            "مدة تنفيذ المشروع: {$timeline} من تاريخ استلام الطرف الأول لكامل متطلبات المشروع من الطرف الثاني.",
                            "مدة البرنامج: {$timeline} من تاريخ الانطلاق المتفق عليه بعد استلام بيانات المتدربين.",
                        )
                        : $t(
                            'يُحدَّد الجدول الزمني للتنفيذ وفق ما اتُّفق عليه في عرض السعر المعتمد.',
                            'يُحدَّد الجدول الزمني للبرنامج وفق ما اتُّفق عليه في عرض السعر المعتمد.',
                        )),
            ],
            [
                'section' => 'المقابل المالي',
                'title' => 'المادة السادسة: قيمة العقد',
                'body' => "القيمة الإجمالية للعقد: {$total} شاملة ضريبة القيمة المضافة إن وُجدت، مقابل "
                    .$t('تنفيذ نطاق العمل الموضَّح في المادة الثانية.', 'تقديم البرنامج الموضَّح في المادة الثانية.'),
            ],
            [
                'section' => 'المقابل المالي',
                'title' => 'المادة السابعة: الدفعات وطريقة السداد',
                'body' => "تُسدَّد قيمة العقد على الدفعات التالية:\n{$payments}\n"
                    .'ويكون السداد عبر التحويل البنكي إلى الحساب الموضَّح في تذييل هذا العقد.',
            ],
            [
                'section' => 'أحكام عامة',
                'title' => $t('المادة الثامنة: الملكية الفكرية وتسليم المصادر', 'المادة الثامنة: المواد التدريبية والملكية الفكرية'),
                'body' => $t(
                    'تنتقل الملكية الفكرية الكاملة للأعمال المنجزة ضمن نطاق هذا العقد إلى الطرف الثاني فور سداد كامل قيمة العقد، ويُسلَّم الطرف الثاني الملفات والصلاحيات اللازمة لإدارة المشروع باستقلالية.',
                    'تبقى حقوق الملكية الفكرية للمواد التدريبية والمناهج للطرف الأول، ويحصل المتدربون على نسخة منها للاستخدام الشخصي، ولا يجوز للطرف الثاني إعادة نشرها أو بيعها أو استخدامها في تدريب أطراف أخرى دون إذن كتابي.',
                ),
            ],
            [
                'section' => 'أحكام عامة',
                'title' => 'المادة التاسعة: السرّية',
                'body' => 'يلتزم كل طرف بالحفاظ على سرّية المعلومات التجارية والفنية التي يطّلع عليها بحكم هذا العقد، وعدم إفشائها لأي طرف ثالث دون إذن كتابي، وتبقى هذه المادة سارية بعد انتهاء العقد.',
            ],
            [
                'section' => 'أحكام عامة',
                'title' => $t('المادة العاشرة: الضمان وحدود المسؤولية', 'المادة العاشرة: الالتزام بالجودة وحدود المسؤولية'),
                'body' => $t(
                    'يقدّم الطرف الأول ضماناً لإصلاح أي عطل تقني ناتج عن التنفيذ لمدة ثلاثين يوماً من تاريخ التسليم، ولا يشمل الضمان أي تعديلات أو إضافات خارج نطاق العمل المتفق عليه. لا يتحمّل الطرف الأول أي مسؤولية عن أضرار غير مباشرة تنتج عن استخدام الطرف الثاني للمشروع.',
                    'يلتزم الطرف الأول بتقديم البرنامج بالجودة والمنهج المتفق عليهما، ويحقّ للطرف الثاني طلب إعادة تقديم أي محور لم يُقدَّم وفق المنهج. لا يضمن الطرف الأول نتائج تعلّم بعينها تعتمد على التزام المتدربين وحضورهم، ولا يتحمّل أي مسؤولية عن أضرار غير مباشرة.',
                ),
            ],
            [
                'section' => 'أحكام عامة',
                'title' => 'المادة الحادية عشرة: إنهاء العقد',
                'body' => 'يجوز لأي من الطرفين إنهاء هذا العقد بإشعار كتابي مسبق مدته أسبوعان في حال إخلال الطرف الآخر بالتزاماته الجوهرية ولم يُصحّح هذا الإخلال خلال مدة معقولة، على أن يُسوَّى المقابل المالي عن الأعمال المنجزة فعلياً حتى تاريخ الإنهاء.',
            ],
            [
                'section' => 'أحكام عامة',
                'title' => 'المادة الثانية عشرة: تسوية النزاعات',
                'body' => 'يسعى الطرفان لتسوية أي خلاف ينشأ عن هذا العقد ودّياً، فإن تعذّر ذلك يكون الاختصاص للجهات القضائية المختصة بجمهورية مصر العربية.',
            ],
            [
                'section' => 'أحكام عامة',
                'title' => 'المادة الثالثة عشرة: أحكام ختامية',
                'body' => 'يمثّل هذا العقد كامل التفاهم بين الطرفين بخصوص المشروع، ولا يُعتدّ بأي تعديل عليه إلا كتابياً وموقَّعاً من الطرفين. حُرِّر هذا العقد من نسختين أصليتين بيد كل طرف نسخة للعمل بموجبها.',
            ],
        ];

        return array_map(fn (array $c, int $i) => [
            'id' => (string) Str::uuid(),
            'section' => $c['section'],
            'title' => $c['title'],
            'body' => $c['body'],
            'order' => $i + 1,
        ], $clauses, array_keys($clauses));
    }
}
