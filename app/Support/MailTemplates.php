    /** مفتاح تخزين القالب في الإعدادات — قوالب المتاجر بمفاتيحها الأصلية حفاظاً على المحفوظ سابقاً. */
    private static function key(string $stage, string $part, string $type): string
    {
        return $type === 'ecommerce' ? "mail_tpl_{$stage}_{$part}" : "mail_tpl_{$type}_{$stage}_{$part}";
    }

    public static function exists(string $stage): bool
    {
        return isset(self::TEMPLATES[$stage]);
    }

    /**
     * النص المقترح للمرحلة بحسب الخدمة: صياغة الخدمة إن وُجدت، وإلا نص المتاجر الافتراضي.
     *
     * @return array{subject: string, body: string}
     */
    public static function defaults(string $stage, string $type = 'ecommerce'): array
    {
        $type = ServiceFlow::type($type);
        $base = self::TEMPLATES[$stage] ?? ['subject' => '', 'body' => ''];
        $variant = self::VARIANTS[$type][$stage] ?? [];

        return [
            'subject' => (string) ($variant['subject'] ?? $base['subject']),
            'body' => (string) ($variant['body'] ?? $base['body']),
        ];
    }

    /** العنوان المحفوظ أو المقترح. */
    public static function subject(string $stage, string $type = 'ecommerce'): string
    {
        $type = ServiceFlow::type($type);

        return (string) Setting::get(self::key($stage, 'subject', $type), self::defaults($stage, $type)['subject']);
    }

    /** النص المحفوظ أو المقترح. */
    public static function body(string $stage, string $type = 'ecommerce'): string
    {
        $type = ServiceFlow::type($type);

        return (string) Setting::get(self::key($stage, 'body', $type), self::defaults($stage, $type)['body']);
    }

    /** هل عُدِّل القالب عن النص المقترح؟ */
    public static function isCustomised(string $stage, string $type = 'ecommerce'): bool
    {
        $defaults = self::defaults($stage, $type);

        return self::subject($stage, $type) !== $defaults['subject']
            || self::body($stage, $type) !== $defaults['body'];
    }

    public static function save(string $stage, string $subject, string $body, string $type = 'ecommerce'): void
    {
        $type = ServiceFlow::type($type);

        Setting::set(self::key($stage, 'subject', $type), trim($subject), 'mail', 'text');
        Setting::set(self::key($stage, 'body', $type), trim($body), 'mail', 'textarea');
    }

    /** استعادة النص المقترح بحذف المحفوظ. */
    public static function reset(string $stage, string $type = 'ecommerce'): void
    {
        $type = ServiceFlow::type($type);
        $defaults = self::defaults($stage, $type);

        Setting::set(self::key($stage, 'subject', $type), $defaults['subject'], 'mail', 'text');
        Setting::set(self::key($stage, 'body', $type), $defaults['body'], 'mail', 'textarea');
    }

