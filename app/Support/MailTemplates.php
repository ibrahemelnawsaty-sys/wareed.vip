            '{الإجمالي}' => $quote ? $money($quote['total'], $quote['currency']) : '—',
            '{موعد_التسليم}' => $flow['due_at']?->format('Y/m/d')
                ?? ($quote['delivery_at'] ?? null)?->format('Y/m/d')
                ?? 'سيُحدَّد لاحقاً',
            '{رقم_العقد}' => $contract['number'] ?? '—',
            '{الجهة}' => (string) ($sr->company ?: 'جهتكم'),
            '{الخدمة}' => ServiceFlow::label($sr),
        ];
    }

    /**
     * إرسال بريد المرحلة إلى العميل — يُستدعى مع كل إجراء ينقل الطلب مرحلةً.
     * يعيد false إن لم يكن للعميل بريد أو تعذّر الإرسال؛ والفشل لا يُعطّل الإجراء نفسه.
     */
    public static function sendStage(ServiceRequest $sr, string $stage, bool $withSummary = false, ?array $attachment = null): bool
    {
        if (! self::exists($stage) || ! filter_var((string) $sr->email, FILTER_VALIDATE_EMAIL)) {
            return false;
        }

        $variables = self::variables($sr);
        $type = ServiceFlow::type($sr);

        // بعض المراحل تحتاج رابط إجراء مباشر بدل رابط المتابعة العام — لعميل الرابط
        // المخصَّص والعميل العام على حدٍّ سواء (رابط المتابعة العام للعميل العام يشير
        // لمستند طلبه لا لصفحة عرض السعر التفاعلية، فلا يصلح لمرحلتين يُنتظر فيهما فعل منه).
        [$link, $linkLabel] = match ($stage) {
            'awaiting_requirements' => [QuoteController::proposalUrl($sr), 'رفع متطلبات المشروع'],
            'awaiting_approval' => [QuoteController::proposalUrl($sr), 'استعراض عرض السعر واعتماده'],
            'contract_draft_sent', 'contract_resent' => [Contracts::reviewUrl($sr), 'مراجعة بنود العقد واعتماده'],
            'contract_approved' => [Contracts::reviewUrl($sr), 'استعراض العقد المعتمد'],
            'contract_signed_sent' => [Contracts::reviewUrl($sr), 'رفع نسختك الموقّعة'],
            default => [$variables['{رابط_الطلب}'], 'متابعة الطلب'],
        };

        try {
            Mail::to($sr->email)->send(new StageMessage(
                subjectLine: self::render(self::subject($stage, $type), $variables),
                bodyText: self::render(self::body($stage, $type), $variables),
                link: $link,
                linkLabel: $linkLabel,
                summaryOf: $withSummary ? $sr : null,
                attachment: $attachment,
            ));

            return true;
        } catch (\Throwable $e) {
            report($e);

            return false;
        }
    }

    /** استبدال المتغيّرات داخل نص. */
    public static function render(string $text, array $variables): string
    {
        return strtr($text, $variables);
    }

    /**
     * تحويل النص المكتوب إلى فقرات HTML آمنة — الأسطر الفارغة تفصل الفقرات.
     */
    public static function html(string $text): string
    {
        $paragraphs = preg_split('/\n\s*\n/u', trim($text)) ?: [];

        return collect($paragraphs)
            ->map(fn ($p) => trim($p))
            ->filter()
            ->map(fn ($p) => '<p style="margin:0 0 14px;color:#55638a;">'.nl2br(e($p)).'</p>')
            ->implode("\n");
    }
